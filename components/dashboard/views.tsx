"use client";
import { useState } from "react";
import {
  Activity,
  ArrowUpRight,
  Coins,
  Database,
  Layers,
  ScanLine,
  Timer,
  Zap,
} from "lucide-react";
import { breakdown, format, money, summarize } from "../../lib/analytics";
import { estimateCost } from "../../lib/pricing";
import { minimumCacheSamples } from "../../lib/diagnostics";
import { recommendations, reviewStatuses } from "../../lib/recommendations";
import type {
  Diagnosis,
  ModelPricing,
  ReviewStatus,
  UsageEvent,
} from "../../types";
import { MascotAssistant } from "../brand";
import { Chart } from "./charts";

export function Overview({
  events,
  pricing,
  findings,
}: {
  events: UsageEvent[];
  pricing: ModelPricing[];
  findings: Diagnosis[];
}) {
  const t = summarize(events, pricing);
  const daily = breakdown(
    events,
    (e) => e.timestamp.slice(0, 10),
    pricing,
  ).sort((a, b) => a.name.localeCompare(b.name));
  const cards = [
    ["Total tokens", format(t.tokens), Layers, "Input and output combined"],
    [
      "Estimated spend",
      t.requests > 0 && t.requests === t.unpriced
        ? "Unavailable"
        : money(t.cost),
      Coins,
      t.unpriced
        ? `${t.unpriced} requests without pricing`
        : "USD · example pricing",
    ],
    ["AI requests", format(t.requests), Activity, "In the selected data"],
    [
      "Average inference latency",
      t.requests ? format(t.latency) + " ms" : "—",
      Timer,
      "Reported in usage records",
    ],
    ["Input tokens", format(t.input), ArrowUpRight, "Includes cached input"],
    ["Output tokens", format(t.output), Zap, "Generated by the model"],
    [
      "Cached input",
      format(t.cached),
      Database,
      t.input
        ? `${format((t.cached / t.input) * 100)}% of input reused`
        : "No input recorded",
    ],
    [
      "Diagnosed inefficiencies",
      format(findings.length),
      ScanLine,
      "Findings with supporting evidence",
    ],
  ] as const;
  return (
    <>
      <div className="metrics">
        {cards.map(([label, value, Icon, caption]) => (
          <section className="panel metric" key={label}>
            <span className="metric-icon">
              <Icon size={17} />
            </span>
            <h2>{label}</h2>
            <strong>{value}</strong>
            <p>{caption}</p>
          </section>
        ))}
      </div>
      <div className="chart-grid">
        <Chart title="Token consumption" rows={daily} trend />
        <Chart
          title="Estimated AI spending"
          rows={daily.filter((row) => row.unpriced < row.requests)}
          metric="cost"
          trend
        />
        <Chart
          title="Tokens by model"
          modelLabels
          rows={breakdown(events, (e) => e.provider + " / " + e.model, pricing)}
        />
        <Chart
          title="Spend by provider"
          rows={breakdown(events, (e) => e.provider, pricing).filter(
            (row) => row.unpriced < row.requests,
          )}
          metric="cost"
        />
        <Chart
          title="Usage by application"
          rows={breakdown(events, (e) => e.application, pricing)}
        />
        <Chart
          title="Cache usage"
          rows={[
            { name: "Cached", tokens: t.cached },
            { name: "Uncached", tokens: t.input - t.cached },
          ]}
        />
        <Chart
          title="Inference latency (ms)"
          rows={daily}
          metric="latency"
          trend
        />
        <Chart
          title="Diagnosis severity"
          rows={["High", "Medium"].map((name) => ({
            name,
            count: findings.filter((f) => f.severity === name).length,
          }))}
          metric="count"
        />
      </div>
    </>
  );
}

export function EventTable({
  events,
  pricing,
}: {
  events: UsageEvent[];
  pricing: ModelPricing[];
}) {
  return (
    <div className="table-scroll">
      <table>
        <thead>
          <tr>
            {[
              "Request / time (UTC)",
              "Provider / model",
              "Application",
              "Input",
              "Output",
              "Cached",
              "Est. USD",
              "Latency",
              "Source",
            ].map((title) => (
              <th key={title}>{title}</th>
            ))}
          </tr>
        </thead>
        <tbody>
          {events.map((e) => {
            const cost = estimateCost(e, pricing);
            return (
              <tr key={e.id}>
                <td>
                  {e.id}
                  <small>{e.timestamp.slice(0, 19).replace("T", " ")}</small>
                </td>
                <td>
                  {e.provider}
                  <small>{e.model}</small>
                </td>
                <td>{e.application}</td>
                <td>{format(e.input)}</td>
                <td>{format(e.output)}</td>
                <td>{format(e.cached)}</td>
                <td>{cost === null ? "Unavailable" : money(cost)}</td>
                <td>{format(e.latency)} ms</td>
                <td>{e.simulated ? "Simulated" : "Imported"}</td>
              </tr>
            );
          })}
        </tbody>
      </table>
      {!events.length && <p className="empty">No requests yet</p>}
    </div>
  );
}
function Evidence({
  finding,
  pricing,
}: {
  finding: Diagnosis;
  pricing: ModelPricing[];
}) {
  return (
    <div className="evidence">
      <dl>
        <dt>Evidence</dt>
        <dd>{finding.evidence}</dd>
        <dt>Detection threshold</dt>
        <dd>{finding.threshold}</dd>
        <dt>Detected at</dt>
        <dd>{new Date(finding.detectedAt).toISOString()}</dd>
        <dt>Why it matters</dt>
        <dd>{finding.why}</dd>
        <dt>Recommended action</dt>
        <dd>
          {finding.action} {finding.steps}
        </dd>
      </dl>
      <EventTable events={finding.events} pricing={pricing} />
    </div>
  );
}
export function Findings({
  findings,
  pricing,
  cacheEvaluated,
  events,
}: {
  findings: Diagnosis[];
  pricing: ModelPricing[];
  cacheEvaluated: boolean;
  events: UsageEvent[];
}) {
  return (
    <div className="stack">
      <div className="panel callout">
        <MascotAssistant />
        <p>
          {events.length
            ? `${findings.length} findings across ${format(events.length)} evaluated requests.`
            : "Insufficient data. Select or import usage records."}
          {events.length > 0 &&
            !events.some(
              (e) =>
                e.task?.toLowerCase() === "classification" &&
                estimateCost(e, pricing) !== null,
            ) && (
              <>
                {" "}
                Cost diagnosis: Insufficient data. Include a priced
                classification request.
              </>
            )}
          {!cacheEvaluated && (
            <>
              {" "}
              Cache diagnosis: Insufficient data. At least {
                minimumCacheSamples
              }{" "}
              requests must share a prefix fingerprint within the same provider,
              model and application.
            </>
          )}
        </p>
      </div>
      {findings.map((f) => (
        <details className="panel finding" key={f.id}>
          <summary>
            <span className={"severity " + f.severity.toLowerCase()}>
              {f.severity}
            </span>
            <span>
              <strong>{f.title}</strong>
              <small>
                {f.events[0].provider} / {f.events[0].model} ·{" "}
                {f.events[0].application}
              </small>
            </span>
            <span>{f.evidence}</span>
          </summary>
          <Evidence finding={f} pricing={pricing} />
        </details>
      ))}
    </div>
  );
}
export function Recommendations({
  findings,
  pricing,
  statuses,
  update,
}: {
  findings: Diagnosis[];
  pricing: ModelPricing[];
  statuses: Record<string, ReviewStatus>;
  update: (id: string, value: ReviewStatus | undefined) => void;
}) {
  return (
    <div className="stack">
      {!findings.length && (
        <p className="panel empty">
          No recommendations for the current selection.
        </p>
      )}
      {recommendations(findings).map(({ id, primary, evidence, requests }) => (
        <section className="panel recommendation" key={id}>
          <div className="section-header">
            <div>
              <span className="eyebrow">{primary.title}</span>
              <h2>{primary.action}</h2>
            </div>
            <select
              aria-label={`Review status for ${primary.title}`}
              value={statuses[id] ?? ""}
              onChange={(e) =>
                update(id, (e.target.value as ReviewStatus) || undefined)
              }
            >
              <option value="">Unreviewed</option>
              {reviewStatuses.map((status) => (
                <option key={status}>{status}</option>
              ))}
            </select>
          </div>
          <p>
            {primary.events[0].application} · {requests} affected requests.{" "}
            {primary.why}
          </p>
          <p>{primary.steps}</p>
          <details>
            <summary>View supporting evidence ({evidence.length})</summary>
            {evidence.map((f) => (
              <Evidence key={f.id} finding={f} pricing={pricing} />
            ))}
          </details>
        </section>
      ))}
    </div>
  );
}

const dimensions: Record<string, (e: UsageEvent) => string> = {
  Model: (e) => e.provider + " / " + e.model,
  Provider: (e) => e.provider,
  Application: (e) => e.application,
  Department: (e) => e.department ?? "Not provided",
  "Day (UTC)": (e) => e.timestamp.slice(0, 10),
  "Hour (UTC)": (e) => e.timestamp.slice(0, 13).replace("T", " ") + ":00",
};
export function Breakdown({
  events,
  pricing,
  findings,
}: {
  events: UsageEvent[];
  pricing: ModelPricing[];
  findings: Diagnosis[];
}) {
  const [dimension, setDimension] = useState("Model");
  const key = dimensions[dimension];
  const rows = breakdown(events, key, pricing).sort(
    (a, b) => b.tokens - a.tokens,
  );
  return (
    <div className="stack">
      <label className="inline-label">
        Group by{" "}
        <select
          value={dimension}
          onChange={(e) => setDimension(e.target.value)}
        >
          {Object.keys(dimensions).map((d) => (
            <option key={d}>{d}</option>
          ))}
        </select>
      </label>
      <Chart
        title={`Token usage by ${dimension.toLowerCase()}`}
        modelLabels={dimension === "Model"}
        rows={rows.slice(0, 10)}
      />
      <div className="panel table-scroll">
        <table>
          <thead>
            <tr>
              {[
                dimension,
                "Total tokens",
                "Input",
                "Output",
                "Cached input",
                "Uncached input",
                "Estimated spend",
                "Findings",
              ].map((name) => (
                <th key={name}>{name}</th>
              ))}
            </tr>
          </thead>
          <tbody>
            {rows.map((row) => (
              <tr key={row.name}>
                <td>{row.name}</td>
                <td>{format(row.tokens)}</td>
                <td>{format(row.input)}</td>
                <td>{format(row.output)}</td>
                <td>{format(row.cached)}</td>
                <td>{format(row.input - row.cached)}</td>
                <td>
                  {row.unpriced === row.requests
                    ? "Unavailable"
                    : money(row.cost) + (row.unpriced ? " (partial)" : "")}
                </td>
                <td>
                  {
                    findings.filter((f) =>
                      f.events.some((e) => key(e) === row.name),
                    ).length
                  }
                </td>
              </tr>
            ))}
          </tbody>
        </table>
      </div>
    </div>
  );
}
